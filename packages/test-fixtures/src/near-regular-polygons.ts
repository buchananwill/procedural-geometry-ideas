/**
 * Symmetric, near-regular, densely sampled polygons: the hardest inputs the straight-skeleton
 * solver has, because exact symmetry lands many collision events on one point at one offset.
 *
 * All seven solve completely. They were added when none of them but the 16-vertex ellipse did,
 * and they remain the regression guard for the coincident-event handling that fixed them — see
 * `packages/core/tests/straight-skeleton/near-regular-polygons.test.ts`.
 *
 * All of these are analytic control shapes — no stroke or random-polygon pipeline is
 * involved. Every one is sampled at uniform angular steps about the centre (300, 300)
 * and stored clockwise (the winding the solver requires), so `solveSkeleton` reports no
 * `winding-normalised` diagnostic for them:
 *
 * | Fixture                    | Parametric definition                | n  |
 * |----------------------------|--------------------------------------|----|
 * | `NEAR_REGULAR_CIRCLE_16`   | r = 150                              | 16 |
 * | `NEAR_REGULAR_CIRCLE_32`   | r = 150                              | 32 |
 * | `NEAR_REGULAR_CIRCLE_48`   | r = 150                              | 48 |
 * | `NEAR_REGULAR_ELLIPSE_16`  | x = 150 cos t, y = 100 sin t         | 16 |
 * | `NEAR_REGULAR_ELLIPSE_32`  | x = 150 cos t, y = 100 sin t         | 32 |
 * | `NEAR_REGULAR_PEANUT_32`   | r = 150 + 55 cos 2t                  | 32 |
 * | `NEAR_REGULAR_ROSETTE5_40` | r = 150 + 45 cos 5t                  | 40 |
 *
 * `NEAR_REGULAR_ELLIPSE_16` was the passing control: same construction, same density band,
 * but it solved before the fix as well as after.
 *
 * The vertices are committed as literals rather than recomputed at import time, because the
 * outcome used to be decided at the last bits of the mantissa: perturbing a failing polygon by
 * 1.5e-7 units (1e-7 % of the radius) was enough to make it pass. A fixture regenerated by
 * `Math.cos` on a different platform would not be the same test.
 *
 * MOSTLY STILL EXCLUDED FROM `ALL_TEST_POLYGONS`. Several suites sweep that list asserting far
 * more than completeness, and promoting all seven was tried and measured again once the peanut's
 * waist was fixed. No blocker is a solver blocker any more; two downstream limits remain, and
 * between them they still block six of the seven:
 *
 *   - `offset-event-boundary-regression.test.ts` cannot close the wavefront at the exact offset
 *     of a many-way event. Blocks `NEAR_REGULAR_ELLIPSE_16`, `NEAR_REGULAR_ELLIPSE_32`,
 *     `NEAR_REGULAR_PEANUT_32` and `NEAR_REGULAR_ROSETTE5_40`. This is a projection limit, not a
 *     solver one: `NEAR_REGULAR_ELLIPSE_16` reports the identical unclosed chain before and
 *     after every solver fix made so far.
 *   - `large-coordinate-failures.test.ts` — 300-unit shapes leave the translation envelope that
 *     file asserts. Blocks `NEAR_REGULAR_CIRCLE_32`, `NEAR_REGULAR_CIRCLE_48` and
 *     `NEAR_REGULAR_ROSETTE5_40`.
 *
 * `NEAR_REGULAR_CIRCLE_16` is blocked by neither and is promotable on its own; promoting it also
 * means updating the hard-coded event-offset count in `offset-event-boundary-regression.test.ts`.
 */

